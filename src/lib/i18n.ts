export const DICTS = { en: EN as Record<Key, string>, tr: TR };

export const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

export function useT() {
  const { lang } = useContext(LangContext);
  return (k: Key, vars?: Record<string, string | number>) => {
    let s = DICTS[lang][k] ?? EN[k];
    if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b));
    return s;
  };
}

export const useLang = () => useContext(LangContext);
